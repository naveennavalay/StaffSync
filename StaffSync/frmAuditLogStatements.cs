        private void chkWrapText_CheckedChanged(object sender, EventArgs e)
        {
            if (dtgAuditLogStatements.Columns.Contains("AuditLogStatement"))
            {
                dtgAuditLogStatements.Columns["AuditLogStatement"].DefaultCellStyle.WrapMode =
                    chkWrapText.Checked ? DataGridViewTriState.True : DataGridViewTriState.False;
            }

            dtgAuditLogStatements.AutoSizeRowsMode = chkWrapText.Checked
                ? DataGridViewAutoSizeRowsMode.AllCells
                : DataGridViewAutoSizeRowsMode.None;

            if (!chkWrapText.Checked)
            {
                foreach (DataGridViewRow row in dtgAuditLogStatements.Rows)
                    row.Height = dtgAuditLogStatements.RowTemplate.Height;
            }
            else
            {
                dtgAuditLogStatements.AutoResizeRows(DataGridViewAutoSizeRowsMode.AllCells);
            }

            dtgAuditLogStatements.Invalidate();
        }

        private void ExportGridToCsv()
        {
            if (dtgAuditLogStatements.Rows.Count == 0)
            {
                MessageBox.Show("There is no audit log data to export.", "Download",
                    MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }

            using (SaveFileDialog saveDialog = new SaveFileDialog())
            {
                string moduleName = string.IsNullOrWhiteSpace(lblFileName.Text)
                    ? "Audit Log Statements"
                    : lblFileName.Text.Trim();
                foreach (char invalid in Path.GetInvalidFileNameChars())
                    moduleName = moduleName.Replace(invalid, '_');

                saveDialog.Title = "Export Audit Log Statements";
                saveDialog.Filter = "CSV files (*.csv)|*.csv|All files (*.*)|*.*";
                saveDialog.FileName = moduleName + " - Audit Log - " + DateTime.Now.ToString("yyyyMMdd_HHmmss") + ".csv";
                saveDialog.DefaultExt = "csv";
                saveDialog.AddExtension = true;
                saveDialog.OverwritePrompt = true;

                if (saveDialog.ShowDialog(this) != DialogResult.OK)
                    return;

                // Export only columns currently visible in the grid.
                // Hidden ID/context columns are intentionally excluded from the CSV.
                using (StreamWriter writer = new StreamWriter(saveDialog.FileName, false, new UTF8Encoding(true)))
                {
                    List<DataGridViewColumn> columns = dtgAuditLogStatements.Columns
                        .Cast<DataGridViewColumn>()
                        .Where(column => column.Visible)
                        .OrderBy(column => column.DisplayIndex)
                        .ToList();

                    writer.WriteLine(string.Join(",", columns.Select(column => CsvEscape(column.HeaderText))));

                    foreach (DataGridViewRow row in dtgAuditLogStatements.Rows)
                    {
                        if (row.IsNewRow) continue;
                        string[] values = columns.Select(column =>
                        {
                            object value = row.Cells[column.Index].FormattedValue;
                            return CsvEscape(value == null ? string.Empty : Convert.ToString(value));
                        }).ToArray();
                        writer.WriteLine(string.Join(",", values));
                    }
                }

                MessageBox.Show("Audit log data exported successfully.", "Download",
                    MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
        }

        private static string CsvEscape(string value)
        {
            if (value == null) return string.Empty;
            return "\"" + value.Replace("\"", "\"\"") + "\"";
        }

