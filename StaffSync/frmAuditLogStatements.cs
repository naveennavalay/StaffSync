        /// <summary>
        /// Draws the attribute name, old value and new value separately so each
        /// part can have its own bold font and colour within the same grid cell.
        /// This changes display only; the stored audit statement is untouched.
        /// </summary>
        private void dtgAuditLogStatements_CellPainting(object sender, DataGridViewCellPaintingEventArgs e)
        {
            if (e.RowIndex < 0 || e.ColumnIndex < 0)
                return;

            if (dtgAuditLogStatements.Columns[e.ColumnIndex].Name != "AuditLogStatement")
                return;

            string statement = Convert.ToString(e.FormattedValue);
            if (string.IsNullOrWhiteSpace(statement))
                return;

            Match match = AuditStatementPattern.Match(statement);
            if (!match.Success)
                return; // Keep normal DataGridView rendering for any other statement format.

            e.PaintBackground(e.CellBounds, true);
            e.Paint(e.CellBounds, DataGridViewPaintParts.Border);

            Color foreColor =
                (e.State & DataGridViewElementStates.Selected) == DataGridViewElementStates.Selected
                ? e.CellStyle.SelectionForeColor
                : e.CellStyle.ForeColor;

            Rectangle textBounds = e.CellBounds;
            textBounds.Inflate(-5, -2);

            // IMPORTANT: Do not dispose e.CellStyle.Font or grid-owned fonts.
            Font regularFont = e.CellStyle.Font ?? dtgAuditLogStatements.Font;

            using (Font boldFont = new Font(regularFont, regularFont.Style | FontStyle.Bold))
            using (SolidBrush normalBrush = new SolidBrush(foreColor))
            using (SolidBrush attributeBrush = new SolidBrush(Color.DarkBlue))
            using (SolidBrush oldValueBrush = new SolidBrush(Color.Red))
            using (SolidBrush newValueBrush = new SolidBrush(Color.Green))
            {
                string attribute = match.Groups["attribute"].Value;
                string oldValue = match.Groups["old"].Value;
                string newValue = match.Groups["new"].Success
                    ? match.Groups["new"].Value
                    : match.Groups["set"].Value;
                bool isChange = match.Groups["old"].Success;

                var segments = new List<AuditTextSegment>
                {
                    new AuditTextSegment("\"" + attribute + "\"", boldFont, attributeBrush),
                    new AuditTextSegment(isChange ? " changed from \"" : " set to \"", regularFont, normalBrush)
                };

                if (isChange)
                {
                    segments.Add(new AuditTextSegment(oldValue, boldFont, oldValueBrush));
                    segments.Add(new AuditTextSegment("\" to \"", regularFont, normalBrush));
                }

                segments.Add(new AuditTextSegment(newValue, boldFont, newValueBrush));
                segments.Add(new AuditTextSegment("\"", regularFont, normalBrush));

                Graphics graphics = e.Graphics;
                GraphicsStatePlaceholder(graphics, () =>
                {
                    graphics.TextRenderingHint = TextRenderingHint.AntiAliasGridFit;
                    if (chkWrapText != null && chkWrapText.Checked)
                        DrawWrappedAuditSegments(graphics, segments, textBounds);
                    else
                        DrawSingleLineAuditSegments(graphics, segments, textBounds);
                });
            }

            e.Handled = true;
        }

        /// <summary>
        /// Executes custom drawing while preserving the original Graphics state.
        /// </summary>
        private static void GraphicsStatePlaceholder(Graphics graphics, Action drawAction)
        {
            System.Drawing.Drawing2D.GraphicsState state = graphics.Save();

            try
            {
                drawAction();
            }
            finally
            {
                graphics.Restore(state);
            }
        }

        private sealed class AuditTextSegment
        {
            public string Text { get; }
            public Font Font { get; }
            public Brush Brush { get; }

            public AuditTextSegment(string text, Font font, Brush brush)
            {
                Text = text ?? string.Empty;
                Font = font;
                Brush = brush;
            }
        }

        private static void DrawSingleLineAuditSegments(Graphics graphics, List<AuditTextSegment> segments, Rectangle bounds)
        {
            float x = bounds.Left;
            float y = bounds.Top + Math.Max(0, (bounds.Height - segments[0].Font.Height) / 2f);
            using (StringFormat format = (StringFormat)StringFormat.GenericTypographic.Clone())
            {
                format.FormatFlags |= StringFormatFlags.MeasureTrailingSpaces | StringFormatFlags.NoWrap;
                foreach (AuditTextSegment segment in segments)
                {
                    if (segment.Text.Length == 0) continue;
                    graphics.DrawString(segment.Text, segment.Font, segment.Brush, x, y, format);
                    x += graphics.MeasureString(segment.Text, segment.Font, PointF.Empty, format).Width;
                }
            }
        }

        private static void DrawWrappedAuditSegments(Graphics graphics, List<AuditTextSegment> segments, Rectangle bounds)
        {
            float x = bounds.Left;
            float y = bounds.Top;
            float lineHeight = segments.Max(segment => segment.Font.Height) + 1f;
            float right = bounds.Right;

            using (StringFormat format = (StringFormat)StringFormat.GenericTypographic.Clone())
            {
                format.FormatFlags |= StringFormatFlags.MeasureTrailingSpaces | StringFormatFlags.NoWrap;
                foreach (AuditTextSegment segment in segments)
                {
                    // Split into words but retain spaces so the statement remains readable.
                    string[] words = Regex.Split(segment.Text, @"(?<=\s)|(?=\s)");
                    foreach (string word in words)
                    {
                        if (word.Length == 0) continue;
                        float wordWidth = graphics.MeasureString(word, segment.Font, PointF.Empty, format).Width;

                        if (x > bounds.Left && x + wordWidth > right)
                        {
                            x = bounds.Left;
                            y += lineHeight;
                        }

                        // Break unusually long values that contain no spaces.
                        if (wordWidth > bounds.Width)
                        {
                            foreach (char ch in word)
                            {
                                string character = ch.ToString();
                                float charWidth = graphics.MeasureString(character, segment.Font, PointF.Empty, format).Width;
                                if (x > bounds.Left && x + charWidth > right)
                                {
                                    x = bounds.Left;
                                    y += lineHeight;
                                }
                                graphics.DrawString(character, segment.Font, segment.Brush, x, y, format);
                                x += charWidth;
                            }
                        }
                        else
                        {
                            graphics.DrawString(word, segment.Font, segment.Brush, x, y, format);
                            x += wordWidth;
                        }
                    }
                }
            }
        }

